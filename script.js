const add = function (num1, num2) {
  if (Number.isInteger(num1) || Number.isInteger(num2)) {
    return num1 + num2;
  }

  alert("Only numbers allowed!");
};

const subtract = function (num1, num2) {
  if (Number.isInteger(num1) || Number.isInteger(num2)) {
    return num1 - num2;
  }

  alert("Only numbers allowed!");
};

const multiply = function (num1, num2) {
  if (Number.isInteger(num1) || Number.isInteger(num2)) {
    return num1 * num2;
  }

  alert("Only numbers allowed!");
};

const divide = function (num1, num2) {
  if (Number.isInteger(num1) || Number.isInteger(num2)) {
    return num1 / num2;
  }

  alert("Only numbers allowed!");
};
